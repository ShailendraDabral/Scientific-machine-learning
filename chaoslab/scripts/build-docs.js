// Generates docs/MODELS.md from the metadata carried by the core modules,
// so the written explanation cannot drift away from the code.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { systems, integrators } from '../src/core/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const equations = {
  lorenz: "dx/dt = sigma (y - x)\ndy/dt = x (rho - z) - y\ndz/dt = x y - beta z",
  rossler: "dx/dt = -y - z\ndy/dt = x + a y\ndz/dt = b + z (x - c)",
  logistic: "x[n+1] = r x[n] (1 - x[n])",
  duffing: "x'' + delta x' + alpha x + beta x^3 = gamma cos(omega t)\n\nfirst-order form, state [x, v]:\nx' = v\nv' = -delta v - alpha x - beta x^3 + gamma cos(omega t)",
  doublePendulum: "state [theta1, theta2, omega1, omega2], D = theta1 - theta2\n\nomega1' = [ -g (2 m1 + m2) sin(theta1) - m2 g sin(theta1 - 2 theta2)\n            - 2 m2 sin(D) (omega2^2 l2 + omega1^2 l1 cos(D)) ] / [ l1 (2 m1 + m2 - m2 cos(2D)) ]\n\nomega2' = [ 2 sin(D) ( omega1^2 l1 (m1 + m2) + g (m1 + m2) cos(theta1)\n            + omega2^2 l2 m2 cos(D) ) ] / [ l2 (2 m1 + m2 - m2 cos(2D)) ]\n\nE = (m1+m2) l1^2 omega1^2 / 2 + m2 l2^2 omega2^2 / 2 + m2 l1 l2 omega1 omega2 cos(D)\n    - (m1+m2) g l1 cos(theta1) - m2 g l2 cos(theta2)",
  threeBody: "r_i'' = G sum_{j != i} m_j (r_j - r_i) / (|r_j - r_i|^2 + eps^2)^(3/2)\n\nE = sum m_i |v_i|^2 / 2 - G sum_{i<j} m_i m_j / r_ij\nP = sum m_i v_i\nL = sum m_i r_i x v_i",
};

let md = '# ChaosLab numerical core: models and methods\n\n'
  + 'Generated by `npm run docs` from the metadata in `src/core`. Do not edit by hand.\n\n'
  + '## Integrators\n\n'
  + '| Method | id | Order | Symplectic | Evaluations per step | Stability limit on dt x rate | Notes |\n'
  + '| --- | --- | --- | --- | --- | --- | --- |\n';
for (const m of Object.values(integrators)) {
  md += `| ${m.name} | \`${m.id}\` | ${m.order} | ${m.symplectic ? 'yes' : 'no'} | ${m.evaluationsPerStep} | ${m.stabilityLimit} | ${m.notes} |\n`;
}
md += '\nThe stability limit is the linear one (test equation y\' = lambda y). "rate" is a per-system upper bound on the fastest '
  + 'local time scale (`rateScale`). It is a necessary condition, not a guarantee: nonlinear systems can still diverge below it, '
  + 'which the solver catches by checking every step for non-finite or runaway values.\n\n'
  + 'Symplectic Euler and Stormer-Verlet are offered only where H = T(p) + V(q): the three-body problem always, the Duffing '
  + 'oscillator when delta = 0. They are refused for the double pendulum, whose kinetic energy depends on the angles.\n\n'
  + '## Models\n';
for (const s of Object.values(systems)) {
  md += `\n### ${s.name}\n\n\`\`\`text\n${equations[s.id]}\n\`\`\`\n\n**Parameters**\n\n| Name | Default | Valid range | Meaning |\n| --- | --- | --- | --- |\n`;
  for (const [k, v] of Object.entries(s.paramSchema)) {
    let range = 'finite';
    if (v.min !== undefined && v.max !== undefined) range = `${v.min} to ${v.max}`;
    else if (v.min !== undefined) range = `${v.minExclusive ? '>' : '>='} ${v.min}`;
    if (k === 'dim') range = '2 or 3';
    if (k === 'masses') range = 'each > 0, at least two';
    const def = Array.isArray(v.default) ? `[${v.default.join(', ')}]` : Number(v.default.toPrecision(6));
    md += `| ${k} | ${def} | ${range} | ${v.description} |\n`;
  }
  md += `\n**Assumptions**\n\n${s.assumptions.map((a) => `- ${a}`).join('\n')}\n`;
  md += `\n**Limitations**\n\n${s.limitations.map((a) => `- ${a}`).join('\n')}\n`;
}
mkdirSync(join(root, 'docs'), { recursive: true });
writeFileSync(join(root, 'docs', 'MODELS.md'), md);
console.log('wrote docs/MODELS.md');
